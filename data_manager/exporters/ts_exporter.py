"""
TypeScript Exporter: compiles Question objects into src/lib/questions.ts
and public/data/questions.json for SamayYudh 2.0.
"""

import json
from pathlib import Path
from typing import List, Optional
from data_manager.models import Question


class TSExporter:
    @staticmethod
    def export_to_typescript(
        questions: List[Question], 
        output_path: Optional[Path] = None
    ) -> Path:
        if output_path is None:
            workspace_root = Path(__file__).resolve().parent.parent.parent
            output_path = workspace_root / "src" / "lib" / "questions.ts"

        output_path.parent.mkdir(parents=True, exist_ok=True)

        # Prepare raw question list
        raw_list = [q.to_dict() for q in questions]
        json_payload = json.dumps(raw_list, indent=2, ensure_ascii=False)

        ts_content = f"""// ============================================================
// SamayYudh 2.0 — Question Bank
// Generated by SamayYudh Python Data Manager
// Total Questions: {len(questions)}
// ============================================================

import {{ Question, ExamCategoryCode, QuestionType, Difficulty }} from '@/types';

type RawQuestionItem = Omit<Question, 'exam_category' | 'question_type'> & {{
  exam_category?: ExamCategoryCode;
  question_type?: QuestionType;
}};

const rawQuestions: RawQuestionItem[] = {json_payload};

export const SAMPLE_QUESTIONS: Question[] = rawQuestions.map((q) => {{
  let qType: QuestionType;
  if ((q as any).question_type) {{
    qType = (q as any).question_type as QuestionType;
  }} else if (q.options && q.options.length > 0) {{
    qType = 'mcq';
  }} else {{
    qType = 'short_answer';
  }}
  return {{
    ...q as any,
    exam_category: ((q as any).exam_category || 'ENGINEERING') as ExamCategoryCode,
    question_type: qType,
  }};
}});

export function getQuestionsByExam(examCode: string): Question[] {{
  return SAMPLE_QUESTIONS.filter((q) => q.exam_code === examCode);
}}

export function getRandomQuestions(count: number, examCode?: string): Question[] {{
  const pool = examCode ? getQuestionsByExam(examCode) : SAMPLE_QUESTIONS;
  if (pool.length <= count) return [...pool];
  const shuffled = [...pool].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}}

export const questionBank = SAMPLE_QUESTIONS;
"""
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(ts_content)

        return output_path

    @staticmethod
    def export_to_json_bundle(
        questions: List[Question], 
        output_path: Optional[Path] = None
    ) -> Path:
        if output_path is None:
            workspace_root = Path(__file__).resolve().parent.parent.parent
            output_path = workspace_root / "public" / "data" / "questions.json"

        output_path.parent.mkdir(parents=True, exist_ok=True)
        raw_list = [q.to_dict() for q in questions]

        with open(output_path, "w", encoding="utf-8") as f:
            json.dump(raw_list, f, indent=2, ensure_ascii=False)

        return output_path
