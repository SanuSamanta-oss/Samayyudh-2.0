"""
Supabase SQL Exporter: generates PostgreSQL schema and bulk INSERT seed statements
for Supabase database integration.
"""

import json
from pathlib import Path
from typing import List, Optional
from data_manager.models import Question


class SQLExporter:
    @staticmethod
    def generate_schema_sql(output_path: Optional[Path] = None) -> Path:
        if output_path is None:
            workspace_root = Path(__file__).resolve().parent.parent.parent
            output_path = workspace_root / "supabase" / "questions_schema.sql"

        output_path.parent.mkdir(parents=True, exist_ok=True)

        sql = """-- ============================================================
-- SamayYudh 2.0 — Questions Table Schema
-- Run in Supabase SQL Editor
-- ============================================================

CREATE TABLE IF NOT EXISTS public.questions (
  id TEXT PRIMARY KEY,
  question_number INT NOT NULL,
  question_text TEXT NOT NULL,
  exam_code TEXT NOT NULL,
  exam_category TEXT NOT NULL DEFAULT 'ENGINEERING',
  subject TEXT NOT NULL,
  topic TEXT NOT NULL DEFAULT 'General',
  subtopic TEXT,
  marks INT NOT NULL DEFAULT 1,
  difficulty TEXT NOT NULL DEFAULT 'medium',
  recommended_minutes INT NOT NULL DEFAULT 2,
  question_type TEXT NOT NULL DEFAULT 'mcq',
  options JSONB,
  correct_answer JSONB,
  expected_points TEXT[] DEFAULT '{}',
  keywords TEXT[] DEFAULT '{}',
  model_answer TEXT DEFAULT '',
  evaluation_rubric TEXT DEFAULT '',
  year TEXT DEFAULT '2024',
  source TEXT,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- Indexes for high-speed practice filtering
CREATE INDEX IF NOT EXISTS idx_questions_exam_code ON public.questions(exam_code);
CREATE INDEX IF NOT EXISTS idx_questions_category ON public.questions(exam_category);
CREATE INDEX IF NOT EXISTS idx_questions_subject ON public.questions(subject);
CREATE INDEX IF NOT EXISTS idx_questions_difficulty ON public.questions(difficulty);
CREATE INDEX IF NOT EXISTS idx_questions_type ON public.questions(question_type);

-- Row Level Security
ALTER TABLE public.questions ENABLE ROW LEVEL SECURITY;

-- Allow public read access to question bank
CREATE POLICY "Anyone can view questions"
  ON public.questions FOR SELECT
  USING (true);

-- Allow service role / admin full write access
CREATE POLICY "Admins can modify questions"
  ON public.questions FOR ALL
  USING (auth.role() = 'service_role')
  WITH CHECK (auth.role() = 'service_role');
"""
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(sql)

        return output_path

    @staticmethod
    def generate_seed_sql(questions: List[Question], output_path: Optional[Path] = None) -> Path:
        if output_path is None:
            workspace_root = Path(__file__).resolve().parent.parent.parent
            output_path = workspace_root / "supabase" / "seed_questions.sql"

        output_path.parent.mkdir(parents=True, exist_ok=True)

        lines = [
            "-- ============================================================",
            f"-- SamayYudh 2.0 — Question Bank Seed ({len(questions)} Questions)",
            "-- Generated by SamayYudh Python Data Manager",
            "-- ============================================================\n"
        ]

        for q in questions:
            # Escape strings for SQL
            q_id = q.id.replace("'", "''")
            q_text = q.question_text.replace("'", "''")
            exam_code = q.exam_code.replace("'", "''")
            exam_category = q.exam_category.replace("'", "''")
            subject = q.subject.replace("'", "''")
            topic = q.topic.replace("'", "''")
            subtopic = f"'{q.subtopic.replace('\'', '\'\'')}'" if q.subtopic else "NULL"
            diff = q.difficulty.replace("'", "''")
            q_type = q.question_type.replace("'", "''")
            model_ans = q.model_answer.replace("'", "''")
            rubric = q.evaluation_rubric.replace("'", "''")
            year = (q.year or "2024").replace("'", "''")

            # JSON fields
            opts_json = "NULL"
            if q.options:
                opts_data = [opt.to_dict() for opt in q.options]
                escaped_opts = json.dumps(opts_data, ensure_ascii=False).replace("'", "''")
                opts_json = f"'{escaped_opts}'::jsonb"

            ans_json = "NULL"
            if q.correct_answer is not None:
                escaped_ans = json.dumps(q.correct_answer, ensure_ascii=False).replace("'", "''")
                ans_json = f"'{escaped_ans}'::jsonb"

            # Array fields
            exp_pts = "ARRAY[" + ", ".join([f"'{p.replace('\'', '\'\'')}'" for p in q.expected_points]) + "]::text[]" if q.expected_points else "'{}'::text[]"
            keywords = "ARRAY[" + ", ".join([f"'{k.replace('\'', '\'\'')}'" for k in q.keywords]) + "]::text[]" if q.keywords else "'{}'::text[]"

            stmt = f"""INSERT INTO public.questions (
  id, question_number, question_text, exam_code, exam_category, subject, topic, subtopic,
  marks, difficulty, recommended_minutes, question_type, options, correct_answer,
  expected_points, keywords, model_answer, evaluation_rubric, year
) VALUES (
  '{q_id}', {q.question_number}, '{q_text}', '{exam_code}', '{exam_category}', '{subject}', '{topic}', {subtopic},
  {q.marks}, '{diff}', {q.recommended_minutes}, '{q_type}', {opts_json}, {ans_json},
  {exp_pts}, {keywords}, '{model_ans}', '{rubric}', '{year}'
) ON CONFLICT (id) DO UPDATE SET
  question_text = EXCLUDED.question_text,
  options = EXCLUDED.options,
  correct_answer = EXCLUDED.correct_answer,
  marks = EXCLUDED.marks,
  difficulty = EXCLUDED.difficulty,
  recommended_minutes = EXCLUDED.recommended_minutes,
  model_answer = EXCLUDED.model_answer,
  evaluation_rubric = EXCLUDED.evaluation_rubric,
  updated_at = now();"""
            lines.append(stmt)

        with open(output_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))

        return output_path
